/**
 * dist/tokens-resolved.json predates this pipeline and is read verbatim by
 * audiobookshelf-now-playing (`app/fujin_tokens.py` resolves
 * `../../Fujin/dist/tokens-resolved.json`). Its shape is therefore a
 * compatibility contract, not a design choice — keep `meta` / `tokens` / `dark`
 * / `light` exactly as they were. New keys are additive and safe; removing or
 * renaming one breaks that consumer.
 */
export const resolvedJsonFormat = {
  name: 'fujin/resolved',
  format({ dictionary, options }) {
    const m = buildModel(dictionary);
    return JSON.stringify(
      {
        meta: {
          version: options.version,
          defaultAccent: m.defaultAccent,
          generated: options.generatedAt,
          description: JSON_BANNER_NOTE,
        },
        tokens: {
          fontFamily: m.scalars.typography.fontFamily.base,
          fontFamilyMono: m.scalars.typography.fontFamily.mono,
        },
        dark: resolveForAccent(m, 'dark', m.defaultAccent),
        light: resolveForAccent(m, 'light', m.defaultAccent),
      },
      null,
      2
    ) + '\n';
  },
};

