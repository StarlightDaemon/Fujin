// Value coercion
// ---------------------------------------------------------------------------

/**
 * DTCG `dimension` values are authored as unit-bearing strings. Two consumers
 * want two different things out of them:
 *   - CSS wants the string verbatim (`16px`, `0.05em`).
 *   - React inline styles and React Native want bare numbers — but only for px,
 *     because `em` has no meaning in RN and web CSS needs the unit preserved.
 * So: px dimensions become numbers in the JS module, everything else stays a
 * string. This reproduces the pre-pipeline token contract exactly.
 */
function jsValue(token) {
  const v = token.$value;
  if (token.$type === 'dimension' && typeof v === 'string' && v.endsWith('px')) {
    return Number.parseFloat(v);
  }
  if (token.$type === 'shadow') return shadowToCss(v);
  return v;
}

function cssValue(token) {
  if (token.$type === 'shadow') return shadowToCss(token.$value);
  return String(token.$value);
}

/** DTCG shadow object -> CSS box-shadow string, omitting zero offsets/spread. */
function shadowToCss(v) {
  const list = Array.isArray(v) ? v : [v];
  return list
    .map((s) => {
      const parts = [trimZero(s.offsetX), trimZero(s.offsetY), trimZero(s.blur)];
      if (s.spread && Number.parseFloat(s.spread) !== 0) parts.push(trimZero(s.spread));
      parts.push(s.color);
      return parts.join(' ');
    })
    .join(', ');
}

/** `0px` -> `0`; anything else unchanged. Matches the hand-authored CSS it replaces. */
const trimZero = (s) => (Number.parseFloat(s) === 0 ? '0' : s);

const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

// ---------------------------------------------------------------------------
// Model — walk the resolved DTCG tree once, produce everything else from it
// ---------------------------------------------------------------------------

const isToken = (n) => n !== null && typeof n === 'object' && '$value' in n;

function walk(node, path, visit) {
  if (isToken(node)) return visit(node, path);
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    walk(child, [...path, key], visit);
  }
}

/**
 * CSS custom-property name for a non-semantic (scalar) token path.
 * Explicit rules, not a generic join — the names are a public contract.
 */
function scalarCssName(path) {
  const p = path.join('.');
  if (p === 'spacing.base') return 'spacing-base';
  if (path[0] === 'spacing' && path[1] === 'scale') return `spacing-${path[2]}`;
  if (path[0] === 'radius') return `radius-${path[1]}`;
  if (path[0] === 'typography') {
    const kind = {
      fontFamily: 'font-family',
      fontSize: 'font-size',
      fontWeight: 'font-weight',
      lineHeight: 'line-height',
      letterSpacing: 'letter-spacing',
    }[path[1]];
    return kind ? `${kind}-${path[2]}` : null;
  }
  if (path[0] === 'opacity') return `opacity-${path[1]}`;
  if (path[0] === 'border' && path[1] === 'width') return `border-width-${path[2]}`;
  if (path[0] === 'layout') return `layout-${path[1]}`;
  if (path[0] === 'breakpoints') return `breakpoint-${path[1]}`;
  if (path[0] === 'transition' && path[1] === 'duration') return `duration-${path[2]}`;
  if (path[0] === 'transition' && path[1] === 'easing') return `easing-${kebab(path[2])}`;
  return null;
}

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

/** Build the single shared model every format below renders from. */
export function buildModel(dictionary) {
  const t = dictionary.tokens;
  const ext = EXT;

  // --- primitive palette: hue -> 10-tuple (plus the `common` singletons) ---
  const palette = {};
  const common = {};
  for (const [hue, ramp] of Object.entries(t.color.palette)) {
    if (hue.startsWith('$')) continue;
    if (hue === 'common') {
      for (const [k, tok] of Object.entries(ramp)) {
        if (!k.startsWith('$')) common[k] = tok.$value;
      }
      continue;
    }
    palette[hue] = Array.from({ length: 10 }, (_, i) => ramp[String(i)].$value);
  }

  // --- semantic roles per mode: `--fujin-<role>` -> resolved value ---
  const semantic = {};
  // Which semantic roles are accent-derived, and at which shade index. Read out
  // of the *unresolved* alias so the mapping stays data-driven: if someone
  // repoints interactive.hover at shade 5, this follows without a code change.
  const accentShades = {};
  for (const mode of ['dark', 'light']) {
    const vars = {};
    walk(t.semantic[mode], [], (token, path) => {
      const name = `--fujin-${path.join('-')}`;
      vars[name] = cssValue(token);
      const ref = token.original?.$value;
      if (typeof ref === 'string') {
        const m = /^\{color\.palette\.([a-z]+)\.(\d)\}$/.exec(ref);
        if (m && m[1] === ext.defaultAccent) accentShades[name] = Number(m[2]);
      }
    });
    semantic[mode] = vars;
  }

  // --- scalars: nested JS model + flat CSS map, from one walk ---
  const scalars = {};
  const scalarCss = {};
  for (const group of ['spacing', 'radius', 'typography', 'opacity', 'border', 'layout', 'breakpoints', 'transition']) {
    walk(t[group], [group], (token, path) => {
      // nested JS shape, camelCasing any hyphenated leaf key
      let cursor = scalars;
      for (const seg of path.slice(0, -1)) cursor = cursor[seg] ??= {};
      cursor[camel(path.at(-1))] = jsValue(token);

      const cssName = scalarCssName(path);
      if (cssName) scalarCss[`--fujin-${cssName}`] = cssValue(token);
    });
  }

  return {
    ext,
    palette,
    common,
    semantic,
    accentShades,
    scalars,
    scalarCss,
    accentOptions: ext.accentOptions ?? [],
    defaultAccent: ext.defaultAccent ?? 'violet',
  };
}

/** Semantic vars for a given mode + accent, applying the accent-shade overrides. */
export function resolveForAccent(model, mode, accent) {
  const ramp = model.palette[accent];
  const out = { ...model.semantic[mode] };
  for (const [name, shade] of Object.entries(model.accentShades)) {
    out[name] = ramp[shade];
  }
  return out;
}

