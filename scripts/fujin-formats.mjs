/**
 * Mantine components whose border-radius is hardcoded in @mantine/core's
 * stylesheet rather than derived from `--mantine-radius-default`. Setting
 * `defaultRadius: 0` on the theme does NOT reach them — each one has its own
 * `--<component>-radius` defaulting to a fully-round 62.5rem/1000rem/50%.
 * Without the per-component defaultProps below, a Fujin-themed app silently
 * renders pill-shaped Badges and circular Avatars inside a system whose
 * canonical radius is 0. Verified against @mantine/core 7.x styles.css.
 */
const ROUNDED_BY_DEFAULT = [
  'Avatar',
  'Badge',
  'Chip',
  'ColorSwatch',
  'Indicator',
  'Pill',
  'RangeSlider',
  'Slider',
  'Stepper',
  'Switch',
  'Timeline',
];

export const mantineFormat = {
  name: 'fujin/mantine',
  format({ dictionary }) {
    const m = buildModel(dictionary);
    const s = m.scalars;

    const px = (n) => `${n}px`;
    const fs = s.typography.fontSize;
    const sp = s.spacing.scale;

    const fontSizes = { xs: px(fs.xs), sm: px(fs.sm), md: px(fs.md), lg: px(fs.lg), xl: px(fs.xl) };
    const spacing = {
      xxs: px(sp.xxs), xs: px(sp.xs), sm: px(sp.sm), md: px(sp.md),
      lg: px(sp.lg), xl: px(sp.xl), xxl: px(sp.xxl),
    };
    const radius = { xs: px(s.radius.xs), sm: px(s.radius.sm), md: px(s.radius.md), lg: px(s.radius.lg), xl: px(s.radius.xl) };

    // Mantine keys line heights xs..xl; Fujin names them by intent. Documented
    // mapping rather than an invented scale: small text is tight, body is base,
    // display text is relaxed.
    const lh = s.typography.lineHeight;
    const lineHeights = { xs: String(lh.tight), sm: String(lh.tight), md: String(lh.base), lg: String(lh.base), xl: String(lh.relaxed) };

    // Mantine v7 expects breakpoints in em. Fujin authors them in px; /16 is the
    // standard root-font-size conversion and reproduces Mantine's own defaults.
    const bp = s.breakpoints;
    const breakpoints = Object.fromEntries(Object.entries(bp).map(([k, v]) => [k, `${v / 16}em`]));

    // Mantine has no per-color-scheme shadow scale. Fujin is dark-first, so the
    // dark shadow set is what the Mantine theme carries; the light values remain
    // available as --fujin-shadow-* for anything that needs them.
    const shadows = Object.fromEntries(
      ['xs', 'sm', 'md', 'lg', 'xl'].map((k) => [k, m.semantic.dark[`--fujin-shadow-${k}`]])
    );

    const components = Object.fromEntries(
      ROUNDED_BY_DEFAULT.map((c) => [c, { defaultProps: { radius: 0 } }])
    );

    return `${BANNER('mantine-theme.js')}
/**
 * Mantine theme object built from tokens.json. Deliberately imports nothing from
 * @mantine/core — @mantine/core is an optional peer dependency, so this module
 * must be loadable by a native-only or CSS-only consumer. Pass the result
 * straight to \`<MantineProvider theme={...}>\`; it satisfies MantineThemeOverride
 * structurally.
 */

import { palette, defaultAccent } from './tokens.js';

/**
 * Mantine components whose radius is hardcoded in @mantine/core's stylesheet and
 * therefore NOT covered by \`defaultRadius\`. Each defaults to a fully-round
 * value; without the defaultProps below, a Fujin-themed app renders pill-shaped
 * Badges and circular Avatars inside a canonical zero-radius system.
 */
export const roundedByDefault = Object.freeze(${lit(ROUNDED_BY_DEFAULT)});

const BASE = Object.freeze({
  fontFamily: ${lit(s.typography.fontFamily.base)},
  fontFamilyMonospace: ${lit(s.typography.fontFamily.mono)},
  headings: {
    fontFamily: ${lit(s.typography.fontFamily.base)},
    fontWeight: ${lit(String(s.typography.fontWeight.semibold))},
    sizes: {
      h1: { fontSize: ${lit(px(fs.h1))}, lineHeight: ${lit(String(lh.tight))} },
      h2: { fontSize: ${lit(px(fs.h2))}, lineHeight: ${lit(String(lh.tight))} },
      h3: { fontSize: ${lit(px(fs.h3))}, lineHeight: ${lit(String(lh.tight))} },
      h4: { fontSize: ${lit(px(fs.h4))}, lineHeight: ${lit(String(lh.base))} },
      h5: { fontSize: ${lit(px(fs.h5))}, lineHeight: ${lit(String(lh.base))} },
      h6: { fontSize: ${lit(px(fs.h6))}, lineHeight: ${lit(String(lh.base))} },
    },
  },
  fontSizes: ${JSON.stringify(fontSizes, null, 2)},
  spacing: ${JSON.stringify(spacing, null, 2)},
  radius: ${JSON.stringify(radius, null, 2)},
  defaultRadius: ${s.radius.default},
  lineHeights: ${JSON.stringify(lineHeights, null, 2)},
  shadows: ${JSON.stringify(shadows, null, 2)},
  breakpoints: ${JSON.stringify(breakpoints, null, 2)},
  colors: palette,
  primaryShade: { light: 6, dark: 6 },
  components: ${JSON.stringify(components, null, 2)},
});

/**
 * Build the Mantine theme override for one accent.
 *
 * Validated against the full palette rather than \`accentOptions\`: every hue is
 * present in \`theme.colors\`, so every hue is a structurally valid Mantine
 * \`primaryColor\`. \`accentOptions\` is the *curated* set Fujin ships a preset for
 * (see themes/index.ts) — a narrower recommendation, not a runtime constraint.
 */
export function createFujinMantineTheme(accent = defaultAccent) {
  if (!Object.prototype.hasOwnProperty.call(palette, accent)) {
    throw new Error(
      \`Unknown Fujin accent: \${accent}. Expected one of: \${Object.keys(palette).join(', ')}\`
    );
  }
  return { ...BASE, primaryColor: accent };
}

export default createFujinMantineTheme;
`;
  },
};

