/** Emit a structural type literal for a plain nested value object. */
function typeLiteral(obj, indent = '  ') {
  const lines = Object.entries(obj).map(([k, v]) => {
    const key = /^[A-Za-z_$][\w$]*$/.test(k) ? k : lit(k);
    if (v !== null && typeof v === 'object') {
      return `${indent}readonly ${key}: {\n${typeLiteral(v, indent + '  ')}\n${indent}};`;
    }
    return `${indent}readonly ${key}: ${typeof v === 'number' ? v : lit(v)};`;
  });
  return lines.join('\n');
}

