const cssBlock = (selector, entries, indent = '  ') =>
  `${selector} {\n` +
  Object.entries(entries).map(([k, v]) => `${indent}${k}: ${v};`).join('\n') +
  `\n}\n`;

export const cssFormat = {
  name: 'fujin/css',
  format({ dictionary }) {
    const m = buildModel(dictionary);

    const paletteVars = {};
    for (const [hue, ramp] of Object.entries(m.palette)) {
      ramp.forEach((v, i) => { paletteVars[`--fujin-palette-${hue}-${i}`] = v; });
    }
    for (const [k, v] of Object.entries(m.common)) {
      paletteVars[`--fujin-palette-common-${k}`] = v;
    }

    const out = [];
    out.push(BANNER('tokens.css').replace(/^\/\*\*/, '/*'));
    out.push(
      `/* Dark is the default mode. Apply light by setting [data-fujin-mode="light"]\n` +
      `   or the .fujin-light class on <html> or any container element.\n` +
      `   Apply a non-default accent with [data-fujin-accent="<name>"] or\n` +
      `   .fujin-accent-<name>. Accents override only the --fujin-interactive-* roles. */\n`
    );

    out.push('/* --- primitive palette (reference only; prefer the semantic roles) --- */');
    out.push(cssBlock(':root', paletteVars));

    out.push('/* --- scale tokens (mode-invariant) --- */');
    out.push(cssBlock(':root', m.scalarCss));

    out.push('/* --- semantic roles: dark (default) --- */');
    out.push(cssBlock(':root, [data-fujin-mode="dark"], .fujin-dark', m.semantic.dark));

    out.push('/* --- semantic roles: light --- */');
    out.push(cssBlock('[data-fujin-mode="light"], .fujin-light', m.semantic.light));

    out.push('/* --- accent presets (override the interactive roles only) --- */');
    for (const accent of m.accentOptions) {
      if (accent === m.defaultAccent) continue;
      const ramp = m.palette[accent];
      const overrides = {};
      for (const [name, shade] of Object.entries(m.accentShades)) overrides[name] = ramp[shade];
      out.push(cssBlock(`[data-fujin-accent="${accent}"], .fujin-accent-${accent}`, overrides));
    }

    return out.join('\n');
  },
};

