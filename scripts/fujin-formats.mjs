// Custom Style Dictionary formats for Fujin.
//
// Why custom formats rather than the built-ins: Fujin's CSS custom-property
// contract (`--fujin-bg-base`, `--fujin-text-primary`, …) predates this pipeline
// and is already consumed byname in downstream repositories. Style Dictionary's
// stock `css/variables` format derives variable names from the full token path,
// which would rename every variable (`--fujin-semantic-dark-bg-base`) and break
// those consumers. So we let Style Dictionary do what only it can do — parse
// DTCG, resolve `{alias.references}`, validate the graph — and keep full control
// of the emitted names here.
//
// Three build targets, one shared value model:
//   fujin/css          -> dist/tokens.css          (CSS custom properties)
//   fujin/js           -> dist/tokens.js           (ESM token module)
//   fujin/dts          -> dist/tokens.d.ts         (types for the above)
//   fujin/mantine      -> dist/mantine-theme.js    (Mantine theme object factory)
//   fujin/mantine-dts  -> dist/mantine-theme.d.ts
//   fujin/resolved     -> dist/tokens-resolved.json (legacy artifact, see below)

import { readFileSync } from 'node:fs';

// Repo-level metadata (accent list, default accent, version namespaces) lives in
// tokens.json's root `$extensions`. It is metadata *about* the token file rather
// than a token, and Style Dictionary drops root-level `$`-prefixed keys from the
// per-platform dictionary it hands to a format — so read it from source instead
// of from `dictionary.tokens`.
const SOURCE = JSON.parse(readFileSync(new URL('../tokens.json', import.meta.url), 'utf8'));
const EXT = SOURCE.$extensions?.['dev.starlightdaemon.fujin'] ?? {};

const BANNER = (file) =>
  `/**\n` +
  ` * ${file}\n` +
  ` *\n` +
  ` * GENERATED FILE — DO NOT EDIT.\n` +
  ` * Source of truth: tokens.json (DTCG). Regenerate with \`npm run build\`.\n` +
  ` * Edits here are lost on the next build and will silently diverge from the\n` +
  ` * token source, which is the exact failure mode CONSUMERS.md exists to prevent.\n` +
  ` */\n`;

const JSON_BANNER_NOTE =
  'Resolved Fujin design tokens. Generated by `npm run build`. Do not edit by hand.';

